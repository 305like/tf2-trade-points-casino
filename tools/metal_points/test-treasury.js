'use strict';
const assert=require('node:assert/strict');
const {value,summary,ownerPayment}=require('./treasury');
const {OWNER}=require('./owner-approval');
const item=(id,name='Refined Metal')=>({appid:440,contextid:'2',assetid:String(id),amount:1,tradable:true,market_hash_name:name});
const inv=[item(1),item(2),item(3)];
assert.equal(value([item(1,'Mann Co. Supply Crate Key')]),5760);
assert.throws(()=>value([item(1,'Rocket Launcher')]));
assert.throws(()=>value([item(1),item(1)]));
const wallet={points:90,withdrawals:90};
assert.equal(summary({},inv,wallet).available,90);
const row={owner:OWNER,kind:'capital_out',price:{keys:0,metal_scrap:9}};
assert.equal(ownerPayment(row,{},inv,wallet,[]).length,1);
assert.equal(ownerPayment({...row,price:{keys:0,metal_scrap:18}},{},inv,wallet,[]),null);
assert.throws(()=>ownerPayment({...row,owner:'76561199077147589'},{},inv,wallet,[]));
assert.equal(summary({shop:{a:{bot_asset:'1',status:'published'}}},inv,wallet).available,0);
assert.equal(summary({},inv,wallet,[{state:2,itemsToGive:[item(1)]}]).available,0);
assert.equal(summary({finance:{x:{kind:'capital_in',done:true,status:'completed',price:row.price}}},inv,wallet).capital_in,90);
console.log('PASS fixed exchange rate, owner-only free capital, liabilities, custody, offer locks and capital ledger totals');
